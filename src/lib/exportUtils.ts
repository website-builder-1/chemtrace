import type { PipelineResults, ReagentInfo, SynthesisRoute } from '@/types/chemtrace';
import { convertFromGBP, fmt, reagentPriceGBP, formatReagentPrice, type Currency } from './currency';

function downloadBlob(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename; a.click();
  URL.revokeObjectURL(url);
}

export function downloadRoutesCSV(results: PipelineResults, currency: Currency = 'GBP') {
  const header = `Route ID,Name,Status,Score,Yield %,Cost/g (${currency}),Batch Estimate (${currency}),Steps,Supply Risk,Regulatory Risk\n`;
  const rows = results.routes.map(r =>
    `${r.id},"${r.name}",${r.status},${r.score},${r.yieldPercent},${convertFromGBP(r.costPerGram, currency)},${convertFromGBP(r.batchEstimate, currency)},${r.steps.length},${r.supplyRisk},${r.regulatoryRisk}`
  ).join('\n');
  downloadBlob(header + rows, `chemtrace_routes_${results.molecule.name.toLowerCase()}.csv`, 'text/csv');
}

export function downloadReagentsCSV(reagents: ReagentInfo[], moleculeName: string, currency: Currency = 'GBP') {
  const header = `Reagent,CAS,Supplier,Country,Price (${currency}),Availability,Lead Days,Hazard,Geo Risk,Status,Export Ctrl\n`;
  const rows = reagents.map(r =>
    `"${r.name}",${r.cas},"${r.supplier}",${r.country},"${formatReagentPrice(r, currency)}",${r.availability},${r.leadDays},"${r.hazard}",${r.geoRisk},${r.status},${r.exportControlled ? 'Yes' : 'No'}`
  ).join('\n');
  downloadBlob(header + rows, `chemtrace_reagents_${moleculeName.toLowerCase()}.csv`, 'text/csv');
}

export function downloadJSON(results: PipelineResults, currency: Currency = 'GBP') {
  const data = { ...results, currency, routes: results.routes.map(r => ({ ...r,
    costPerGram: convertFromGBP(r.costPerGram, currency), batchEstimate: convertFromGBP(r.batchEstimate, currency),
    reagentProcurement: r.reagentProcurement.map(p => ({ ...p, price: formatReagentPrice(p, currency),
      unitPrice: reagentPriceGBP(p) == null ? undefined : convertFromGBP(reagentPriceGBP(p) ?? 0, currency), priceCurrency: currency,
    })),
  })) };
  downloadBlob(JSON.stringify(data, null, 2), `chemtrace_${results.molecule.name.toLowerCase()}.json`, 'application/json');
}

export function downloadCROBrief(results: PipelineResults, currency: Currency = 'GBP') {
  const rec = results.routes.find(r => r.id === results.recommendedRouteId);
  if (!rec) return;
  const brief = `CRO SYNTHESIS BRIEF
Generated by Chemtraceit — ${new Date().toISOString().slice(0, 10)}
${'═'.repeat(60)}

TARGET MOLECULE: ${results.molecule.name}
SMILES: ${results.molecule.smiles}
IUPAC: ${results.molecule.iupac}
MW: ${results.molecule.mw} g/mol
BATCH SIZE: ${results.batchSizeMg} mg
PRODUCTION LOCATION: ${results.location}

${'─'.repeat(60)}
RECOMMENDED ROUTE: ${rec.name}
STATUS: ${rec.status}
ESTIMATED YIELD: ${rec.yieldPercent}%
CURRENCY: ${currency} (indicative reference conversion)
COST PER GRAM: ${fmt(rec.costPerGram, currency)}
BATCH COST ESTIMATE: ${fmt(rec.batchEstimate, currency)}

SYNTHESIS STEPS:
${rec.steps.map(s => `  ${s.number}. ${s.description}`).join('\n')}

REAGENTS: ${rec.reagents.join(', ')}

LITERATURE: ${rec.citation}

SUPPLY RISK: ${rec.supplyRisk}
REGULATORY RISK: ${rec.regulatoryRisk}
DECISION: ${rec.decisionReason}
`;
  downloadBlob(brief, `chemtrace_cro_brief_${results.molecule.name.toLowerCase()}.txt`, 'text/plain');
}

export function generateInvoiceData(route: SynthesisRoute, batchMg: number, currency: Currency = 'GBP') {
  const items = route.reagentProcurement.map(r => {
    const basePrice = reagentPriceGBP(r);
    const unitPrice = basePrice == null ? null : convertFromGBP(basePrice, currency);
    const qty = Math.max(1, Math.ceil(batchMg / 500));
    return { reagent: r.name, cas: r.cas, supplier: r.supplier, unitPrice, qty, total: unitPrice == null ? null : +(unitPrice * qty).toFixed(2) };
  });
  const subtotal = items.reduce((s, i) => s + (i.total ?? 0), 0);
  const vat = +(subtotal * 0.20).toFixed(2);
  return { items, currency, incomplete: items.some(i => i.unitPrice == null), subtotal: +subtotal.toFixed(2), vat, grandTotal: +(subtotal + vat).toFixed(2), invoiceNumber: `CT-${Date.now().toString(36).toUpperCase()}`, date: new Date().toISOString().slice(0, 10) };
}
